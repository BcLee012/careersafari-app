def boundary_problems(family, tasks):
    """Conservative veto for a known failure; never infer/reassign a family from titles.

    Two separate explicit algorithm construction duties with no analysis-report output
    contradict the three report-oriented families. This is a limited guard, not a
    replacement for semantic classification or a claim to catch all mistakes.
    """
    if family not in ("数据分析", "商业/经营分析", "战略分析"):
        return []
    tasks = [t for t in tasks if isinstance(t, str)]
    algorithm = sum(bool(re.search(r"(算法.{0,35}(研发|开发|建设|构建)|(?:研发|开发|建设|构建|制定).{0,45}算法)", t)) for t in tasks)
    report = any(re.search(r"(分析报告|研究报告|经营诊断|分析看板|决策建议|实验结论)", t) for t in tasks)
    if algorithm >= 2 and not report:
        return ["主要职责包含多项算法建设且没有分析报告类产出，不能自动归入分析岗位族；需按目录外岗位或待分类处理"]
    return []
